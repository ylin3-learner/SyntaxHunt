#!/usr/bin/env node
// Zero-dependency intelligent git push with automatic rebase, merge fallback & map sync
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

function run(cmd, args, cwd = process.cwd(), stdio = 'pipe') {
  return execFileSync(cmd, args, { cwd, stdio, encoding: 'utf8' });
}

function isAutoGeneratedFile(filePath) {
  const norm = filePath.replace(/\\/g, '/');
  return (
    norm === 'PROJECT_MAP.md' ||
    norm === 'PROGRESS.md' ||
    norm === 'README.md' ||
    norm === 'README.zh-TW.md' ||
    norm.startsWith('.cartographer/')
  );
}

function main() {
  const ROOT = process.cwd();

  const dirty = run('git', ['status', '--porcelain'], ROOT).trim();
  if (dirty) {
    console.error('❌ [git-sync] Aborted: working tree has uncommitted changes. Commit or stash first.\n' + dirty);
    process.exit(1);
  }

  const branch = run('git', ['rev-parse', '--abbrev-ref', 'HEAD'], ROOT).trim() || 'main';

  // 1. Fast path: try direct push first
  try {
    console.log(`🚀 [git-sync] Pushing ${branch} to origin...`);
    const out = run('git', ['push', 'origin', branch], ROOT, 'pipe');
    if (out) process.stdout.write(out);
    console.log(`🎉 [git-sync] Synced and pushed ${branch} successfully!`);
    return;
  } catch (err) {
    const errText = ((err.stderr || '') + (err.stdout || '') + (err.message || '')).toLowerCase();
    const isBehind =
      errText.includes('fetch first') ||
      errText.includes('non-fast-forward') ||
      errText.includes('rejected');

    if (!isBehind) {
      console.error('❌ [git-sync] Push failed with non-rebase error.');
      process.exit(1);
    }
    console.log(`🔄 [git-sync] Remote has new commits. Pulling & integrating origin/${branch}...`);
  }

  // 2. Try rebase --autostash first; if mid-replay dirty/conflict occurs, abort & merge cleanly
  let rebased = false;
  try {
    run('git', ['pull', '--rebase', '--autostash', 'origin', branch], ROOT, 'inherit');
    rebased = true;
  } catch {
    try {
      run('git', ['rebase', '--abort'], ROOT);
    } catch {}
    console.log('🛠️ [git-sync] Rebase interrupted; falling back to safe merge integration...');
    try {
      run('git', ['pull', '--no-rebase', '--no-edit', 'origin', branch], ROOT, 'inherit');
    } catch {
      const unmergedOut = run('git', ['diff', '--name-only', '--diff-filter=U'], ROOT).trim();
      const conflicts = unmergedOut ? unmergedOut.split(/\r?\n/).filter(Boolean) : new Array();
      if (conflicts.length > 0 && conflicts.every(isAutoGeneratedFile)) {
        for (const f of conflicts) {
          try { run('git', ['checkout', '--ours', f], ROOT); } catch {}
        }
        run('git', ['add', '-A'], ROOT);
        run('git', ['commit', '--no-verify', '-m', 'chore(harness): resolve generated map merge'], ROOT);
      } else {
        console.error('❌ [git-sync] Real code conflict detected in:', conflicts.join(', '));
        process.exit(1);
      }
    }
  }

  // 3. Refresh map once after integration finishes cleanly
  const syncScript = path.join(ROOT, '.harness', 'scripts', 'sync-map.mjs');
  if (fs.existsSync(syncScript)) {
    run(process.execPath, [syncScript], ROOT, 'inherit');
    run('git', ['add', '.cartographer', 'PROJECT_MAP.md'], ROOT);
    const diff = run('git', ['diff', '--cached', '--name-only'], ROOT).trim();
    if (diff) {
      run('git', ['commit', '--no-verify', '-m', 'chore(harness): refresh map after sync'], ROOT);
    }
  }

  // 4. Push integrated commits
  console.log(`🚀 [git-sync] Pushing synced ${branch} to origin...`);
  run('git', ['push', 'origin', branch], ROOT, 'inherit');
  console.log(`🎉 [git-sync] Synced and pushed ${branch} successfully!`);
}

main();
