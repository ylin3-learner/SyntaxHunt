import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const HANDOFF_FILE = 'HANDOFF.md';
const BLOCKERS_MARKER = '## Current Blockers & Next Actions';
const NL = String.fromCharCode(10);

function runGit(args) {
  try {
    return execSync('git ' + args, { encoding: 'utf8', stdio: 'pipe' }).trim();
  } catch {
    return '(git command failed or not a repository)';
  }
}

const status = runGit('status -s');
const diffStat = runGit('diff --stat');

let verifyState = null;
if (existsSync('.verify-state.json')) {
  try {
    verifyState = JSON.parse(readFileSync('.verify-state.json', 'utf8'));
  } catch {
    verifyState = null;
  }
}

let preservedTail = '';
if (existsSync(HANDOFF_FILE)) {
  try {
    const existing = readFileSync(HANDOFF_FILE, 'utf8');
    const idx = existing.indexOf(BLOCKERS_MARKER);
    if (idx !== -1) preservedTail = existing.slice(idx);
  } catch {
    preservedTail = '';
  }
}

const lines = [];
lines.push('# HANDOFF');
lines.push('');
lines.push('_Auto-generated by `node scripts/handoff-pack.mjs` at ' + new Date().toISOString() + '_');
lines.push('');
lines.push('## Objective State');
lines.push('');
lines.push('### Git Working Tree (`git status -s`)');
if (status) {
  for (const line of status.split(NL)) lines.push('- ' + line);
} else {
  lines.push('- (clean working tree)');
}
lines.push('');
lines.push('### Diff Stat (`git diff --stat`)');
if (diffStat) {
  for (const line of diffStat.split(NL)) lines.push('- ' + line);
} else {
  lines.push('- (no unstaged changes)');
}
lines.push('');
lines.push('### Verify State (`.verify-state.json`)');
if (verifyState) {
  lines.push('- Gate: ' + (verifyState.gate || '(none)'));
  lines.push('- Consecutive failures: ' + (verifyState.count != null ? verifyState.count : 0));
  lines.push('- Error hash: ' + (verifyState.hash || ''));
  if (verifyState.lastFailedAt) lines.push('- Last failed at: ' + verifyState.lastFailedAt);
  if (verifyState.lastPassedAt) lines.push('- Last passed at: ' + verifyState.lastPassedAt);
} else {
  lines.push('- (no verify state recorded)');
}
lines.push('');
lines.push('---');
lines.push('');

if (preservedTail) {
  lines.push(preservedTail);
} else {
  lines.push(BLOCKERS_MARKER);
  lines.push('');
  lines.push('<!-- LLM: add up to 3 sentences about current blockers and next actions below this line -->');
  lines.push('');
}

const content = lines.join(NL);
writeFileSync(HANDOFF_FILE, content, 'utf8');
console.log('Generated HANDOFF.md');
console.log('');
console.log(content);